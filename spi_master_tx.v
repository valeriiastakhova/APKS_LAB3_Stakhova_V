`timescale 1ns / 1ps

// ============================================================================
// Модуль: spi_master_tx
// Опис:   Передавач (Master) інтерфейсу SPI (Mode 0: CPOL=0, CPHA=0, 8 біт, MSB)
//         Генерує тактовий сигнал SCK, керує вибором пристрою CS_N,
//         передає байт по MOSI та одночасно приймає відповідь по MISO.
// ============================================================================
module spi_master_tx #(
    parameter integer CLK_DIV = 8  // Коефіцієнт поділу частоти для півперіоду SCK
                                   // F_sck = F_clk / (2 * CLK_DIV)
)(
    // Системні сигнали
    input  wire       clk,         // Системний тактовий сигнал ПЛІС (напр. 100 МГц)
    input  wire       rst_n,       // Асинхронний скид (активний низький рівень '0')
    
    // Інтерфейс користувача (внутрішня шина ПЛІС)
    input  wire       start,       // Сигнал запуску передачі (активний '1')
    input  wire [7:0] tx_data,     // 8-бітні дані для передачі по лінії MOSI
    output reg  [7:0] rx_data,     // 8-бітні прийняті дані з лінії MISO
    output reg        busy,        // Прапорець зайнятості ('1' - йде обмін)
    output reg        done,        // Імпульс завершення передачі (на 1 такт clk)
    
    // Фізичні лінії інтерфейсу SPI
    output reg        sck,         // Тактовий сигнал шини SPI
    output reg        mosi,        // Вихід даних від Master до Slave
    input  wire       miso,        // Вхід даних від Slave до Master
    output reg        cs_n         // Вибір ведомого пристрою (активний '0')
);

    // Кодування станів скінченного автомата (FSM)
    localparam [1:0] STATE_IDLE     = 2'b00; // Очікування команди запуску
    localparam [1:0] STATE_TRANSFER = 2'b01; // Активна передача/прийом 8 біт
    localparam [1:0] STATE_FINISH   = 2'b10; // Завершення транзакції та зняття CS_N

    // Внутрішні регістри
    reg [1:0]  state;       // Поточний стан автомата
    reg [7:0]  tx_shift;    // Зсувний регістр передачі
    reg [7:0]  rx_shift;    // Зсувний регістр прийому
    reg [2:0]  bit_cnt;     // Лічильник переданих бітів (від 7 до 0)
    reg [15:0] clk_cnt;     // Лічильник дільника частоти для формування SCK

    // Основний послідовнісний блок керування FSM та шиною SPI
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // Початкове скидання всіх регістрів та виходів у безпечний стан
            state    <= STATE_IDLE;
            tx_shift <= 8'd0;
            rx_shift <= 8'd0;
            rx_data  <= 8'd0;
            bit_cnt  <= 3'd0;
            clk_cnt  <= 16'd0;
            sck      <= 1'b0; // CPOL = 0: у стані спокою SCK = 0
            mosi     <= 1'b0;
            cs_n     <= 1'b1; // Деактивація ведомого пристрою
            busy     <= 1'b0;
            done     <= 1'b0;
        end else begin
            // Прапорець done формується як одиночний строб тривалістю 1 такт clk
            done <= 1'b0;

            case (state)
                // ------------------------------------------------------------
                // 1. Стан очікування (IDLE)
                // ------------------------------------------------------------
                STATE_IDLE: begin
                    sck  <= 1'b0;
                    cs_n <= 1'b1;
                    busy <= 1'b0;

                    if (start) begin
                        tx_shift <= tx_data;      // Фіксуємо вхідний байт
                        rx_shift <= 8'd0;         // Очищаємо приймальний буфер
                        bit_cnt  <= 3'd7;         // Починаємо зі старшого біта (MSB)
                        clk_cnt  <= 16'd0;
                        cs_n     <= 1'b0;         // Опускаємо CS_N для початку обміну
                        mosi     <= tx_data[7];   // Виставляємо 7-й біт на MOSI заздалегідь (CPHA=0)
                        busy     <= 1'b1;
                        state    <= STATE_TRANSFER;
                    end
                end

                // ------------------------------------------------------------
                // 2. Стан передачі та прийому даних (TRANSFER)
                // ------------------------------------------------------------
                STATE_TRANSFER: begin
                    if (clk_cnt == CLK_DIV - 1) begin
                        clk_cnt <= 16'd0;

                        if (sck == 1'b0) begin
                            // Формуємо НАРОСТАЮЧИЙ фронт SCK (0 -> 1)
                            // У режимі Mode 0 по передньому фронту відбувається вибірка даних
                            sck      <= 1'b1;
                            rx_shift <= {rx_shift[6:0], miso}; // Зчитуємо біт із лінії MISO
                        end else begin
                            // Формуємо СПАДАЮЧИЙ фронт SCK (1 -> 0)
                            // У режимі Mode 0 по задньому фронту змінюємо дані на лінії MOSI
                            sck <= 1'b0;

                            if (bit_cnt == 3'd0) begin
                                // Усі 8 бітів передано та прийнято
                                state <= STATE_FINISH;
                            end else begin
                                bit_cnt <= bit_cnt - 1'b1;
                                mosi    <= tx_shift[bit_cnt - 1'b1]; // Виставляємо наступний біт
                            end
                        end
                    end else begin
                        clk_cnt <= clk_cnt + 1'b1;
                    end
                end

                // ------------------------------------------------------------
                // 3. Стан завершення транзакції (FINISH)
                // ------------------------------------------------------------
                STATE_FINISH: begin
                    // Витримуємо паузу півперіоду SCK перед підняттям CS_N
                    if (clk_cnt == CLK_DIV - 1) begin
                        clk_cnt <= 16'd0;
                        cs_n    <= 1'b1;      // Знімаємо вибір ведомого пристрою
                        mosi    <= 1'b0;
                        rx_data <= rx_shift;  // Видаємо прийнятий байт на вихідний порт
                        busy    <= 1'b0;
                        done    <= 1'b1;      // Сигналізуємо про завершення
                        state   <= STATE_IDLE;
                    end else begin
                        clk_cnt <= clk_cnt + 1'b1;
                    end
                end

                default: state <= STATE_IDLE;
            endcase
        end
    end

endmodule